"""Collect versioned upstream sources beside the image's release records.

Input is generated by release-inventory.py from a clean image. This script never
reads an application data directory. Downloads are not executed or installed.
"""
import argparse
from concurrent.futures import ThreadPoolExecutor, as_completed
import hashlib
import json
from pathlib import Path
import re
import tarfile
import time
from urllib.error import HTTPError
from urllib.parse import quote, urlencode, urlsplit, unquote
from urllib.request import Request, urlopen


def request(url):
    return urlopen(Request(url, headers={"User-Agent": "buzz-unraid-source-collector/1"}), timeout=90)


def get_json(url):
    for attempt in range(3):
        try:
            with request(url) as response:
                return json.load(response)
        except HTTPError as error:
            if error.code == 404:
                raise
            if attempt == 2:
                raise
        except OSError:
            if attempt == 2:
                raise
        time.sleep(2 * (attempt + 1))


def download(entry, directory):
    url = entry["url"]
    basename = unquote(urlsplit(url).path.rsplit("/", 1)[-1])
    basename = re.sub(r"[^A-Za-z0-9._+-]", "_", basename) or "source.archive"
    filename = re.sub(r"[^A-Za-z0-9._+-]", "_", entry["component"]) + "--" + basename
    path = directory / filename
    for attempt in range(3):
        digest = hashlib.sha256()
        try:
            with request(url) as response, path.open("wb") as target:
                while data := response.read(1024 * 1024):
                    digest.update(data)
                    target.write(data)
            value = digest.hexdigest()
            if entry.get("sha256") and value != entry["sha256"]:
                raise ValueError(f"Source hash mismatch: {entry['component']}")
            return {**entry, "file": filename, "sha256": value, "bytes": path.stat().st_size}
        except (OSError, HTTPError):
            if attempt == 2:
                raise
            time.sleep(2 * (attempt + 1))


def python_source(package):
    name = package["name"]
    version = package["version"].split("+")[0]
    if name.lower().startswith("nvidia-"):
        return [], {"name": name, "version": package["version"], "source": "NVIDIA proprietary runtime; installed license retained"}
    data = get_json(f"https://pypi.org/pypi/{quote(name)}/{quote(version)}/json")
    sdists = [item for item in data["urls"] if item["packagetype"] == "sdist"]
    if sdists:
        item = sdists[0]
        return [{"component": name + "-" + version, "url": item["url"],
                 "sha256": item["digests"]["sha256"], "origin": "PyPI versioned source distribution"}], None
    if name.lower() in ("torch", "torchaudio", "pyqt6-qt6", "lameenc"):
        return [], {"name": name, "version": package["version"], "source": "Pinned upstream source archive in source-archives.json"}
    license_info = json.dumps(package.get("license_classifiers", [])) + package.get("license_expression", "") + json.dumps(package.get("license_summary", []))
    if re.search(r"(?i)(GPL|General Public License|MPL)", license_info):
        raise ValueError(f"No source distribution for copyleft package {name} {version}; add an exact source archive")
    return [], {"name": name, "version": package["version"], "source": "No PyPI source distribution; installed notices retained", "project_urls": package["project_urls"]}


def ubuntu_source(package):
    params = urlencode({"ws.op": "getPublishedSources", "source_name": package["source_name"],
                        "version": package["source_version"], "exact_match": "true"})
    data = get_json("https://api.launchpad.net/1.0/ubuntu/+archive/primary?" + params)
    entries = data.get("entries", [])
    if not entries:
        raise ValueError(f"Exact Ubuntu source unavailable: {package['source_name']} {package['source_version']}")
    urls = get_json(entries[0]["self_link"] + "?ws.op=sourceFileUrls")
    return [{"component": package["source_name"] + "-" + package["source_version"],
             "url": url, "origin": "Ubuntu official source publication / " + entries[0]["self_link"]} for url in urls]


def source_notices(archive, destination):
    if not tarfile.is_tarfile(archive):
        return
    with tarfile.open(archive) as source:
        for member in source:
            if not member.isfile() or member.size > 2_000_000:
                continue
            if not re.match(r"(?i)^(?:copying|license|licence|copyright|notice)(?:[._-].*)?$", Path(member.name).name):
                continue
            # Construct a fresh relative path; never extract untrusted archives.
            safe_parts = [p for p in Path(member.name).parts if p not in ("..", "/", ".")]
            target = destination.joinpath(*safe_parts)
            target.parent.mkdir(parents=True, exist_ok=True)
            content = source.extractfile(member)
            if content:
                target.write_bytes(content.read())


class PartsWriter:
    def __init__(self, directory, limit=512 * 1024 * 1024):
        self.directory, self.limit, self.part, self.used = directory, limit, -1, 0
        self.file = None

    def write(self, data):
        total = len(data)
        while data:
            if self.file is None or self.used == self.limit:
                if self.file:
                    self.file.close()
                self.part += 1
                self.file = (self.directory / f"sources.tar.part{self.part:03d}").open("wb")
                self.used = 0
            size = min(len(data), self.limit - self.used)
            self.file.write(data[:size])
            self.used += size
            data = data[size:]
        return total

    def close(self):
        if self.file:
            self.file.close()


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("inventory", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("--archives", type=Path, default=Path("requirements/source-archives.json"))
    args = parser.parse_args()
    inventory = json.loads(args.inventory.read_text())
    expected = {p["name"].lower(): p["version"] for p in inventory["python"]}
    for name, version in {"pyqt6-qt6": "6.9.1", "av": "19.0.2", "torch": "2.8.0+cu126", "torchaudio": "2.8.0+cu126", "lameenc": "1.9.0"}.items():
        if expected.get(name) != version:
            raise ValueError(f"Review pinned source archives for changed {name}: {expected.get(name)}")
    output = args.output
    archives = output / "source-files"
    archives.mkdir(parents=True, exist_ok=True)
    entries = json.loads(args.archives.read_text())["archives"]
    exceptions = []
    failures = []
    with ThreadPoolExecutor(max_workers=8) as pool:
        jobs = {pool.submit(python_source, p): p["name"] for p in inventory["python"]}
        for future in as_completed(jobs):
            try:
                found, exception = future.result()
                entries.extend(found)
                if exception:
                    exceptions.append(exception)
            except Exception as error:
                failures.append(f"{jobs[future]}: {error}")
        system = {(p["source_name"], p["source_version"]): p for p in inventory["ubuntu"] if p["copyleft_notice"]}
        jobs = {pool.submit(ubuntu_source, p): key for key, p in system.items()}
        for future in as_completed(jobs):
            try:
                entries.extend(future.result())
            except Exception as error:
                failures.append(f"{jobs[future]}: {error}")
    unique = {e["url"]: e for e in entries}
    records = []
    with ThreadPoolExecutor(max_workers=8) as pool:
        jobs = {pool.submit(download, entry, archives): entry["component"] for entry in unique.values()}
        for future in as_completed(jobs):
            try:
                record = future.result()
                records.append(record)
                print(f"Source OK: {record['component']} ({record['bytes']} bytes)", flush=True)
            except Exception as error:
                failures.append(f"{jobs[future]}: {error}")
    manifest = {"schema": 1, "archives": sorted(records, key=lambda r: r["file"]),
                "packages_without_sdist": sorted(exceptions, key=lambda r: r["name"]), "failures": failures}
    (output / "source-manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    if failures:
        raise SystemExit("Source collection incomplete:\n" + "\n".join(failures))
    for record in records:
        source_notices(archives / record["file"], output / "notices/upstream" / record["component"])
    writer = PartsWriter(output)
    try:
        with tarfile.open(fileobj=writer, mode="w|") as bundle:
            for path in sorted(archives.iterdir()):
                bundle.add(path, arcname="sources/" + path.name, recursive=False)
    finally:
        writer.close()
    with tarfile.open(output / "notices.tar.gz", "w:gz") as bundle:
        bundle.add(output / "notices", arcname="notices")
    (output / "SOURCE-README.txt").write_text(
        "Matching upstream archives, build recipes and installed notices for this release.\n"
        "Download every sources.tar.partNNN asset into one directory, then run:\n"
        "  cat sources.tar.part* | tar -xf -\n"
        "Individual archive origins and SHA-256 hashes are in source-manifest.json.\n"
        "Container source and patches are in the release's GitHub Source code archive.\n"
        "Ubuntu .dsc, original archives and Debian patches are supplied together.\n"
        "Keep original licenses when modifying or redistributing components.\n")
    checksums = []
    for path in sorted(output.iterdir()):
        if path.is_file() and path.name != "SHA256SUMS":
            digest = hashlib.file_digest(path.open("rb"), "sha256").hexdigest()
            checksums.append(f"{digest}  {path.name}")
    (output / "SHA256SUMS").write_text("\n".join(checksums) + "\n")


if __name__ == "__main__":
    main()
